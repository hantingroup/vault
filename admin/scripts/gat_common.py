"""港澳台数据的共用部分：type 与「专名:通名」的写法。

港澳台的 type 不跟大陆的行政区划分类对齐（台湾没有地级市，省辖市就是「市」，
县下是「縣轄市」），跟名字一样照页面原文写繁体。citypopulation.de 和
dsec.gov.mo 两个更新脚本都用这里的函数把页面上的写法转成仓库格式。
"""

# TYPES 里统一用简体键，输出前查这张表换成繁体
TRAD_TYPE = {
    '省': '省', '特别行政区': '特別行政區',
    '直辖市': '直轄市', '县': '縣', '市辖区': '市轄區',
    '市': '市', '县辖市': '縣轄市', '镇': '鎮', '乡': '鄉',
    '区议会': '區議會', '选区': '選區',
    '堂区': '堂區', '区': '區', '统计区': '統計區', '区域': '區域',
}

# type -> 名字末尾那个通名。None 表示这类单位名字里不带通名，原样留着（香港的选区
# 是「宝翠」「卫城」这种，没有通名可切）。页面原文是繁体，通名也按繁体比。
SUFFIX = {
    '省': '省', '特别行政区': '特別行政區',
    '直辖市': '市', '县': '縣', '市辖区': '區',
    '市': '市', '县辖市': '市', '镇': '鎮', '乡': '鄉', '区域': '區域',
    '区议会': '區', '选区': None,
    '堂区': '堂區', '区': '區', '统计区': '統計區',
}


def type_out(type_):
    """输出用的 type：统一换成页面原文的繁体；表里没有的自定义 type 原样"""
    return TRAD_TYPE.get(type_, type_)


def split_name(name, type_):
    """把页面名字切成本仓库的「专名:通名」

    有两处页面名字里没有通名或通名写残了，切之前先补回来：
        堂区  页面把「堂區」写成「堂」（花地瑪堂、聖安多尼堂…），先补掉那个堂。
              「大堂」不补——剥了只剩一个「大」字，那个堂是名字的一部分
        区议会  页面漏了「深水埗」的「區」（其余 17 个都有），按通名补上
    """
    suffix = SUFFIX[type_]
    if suffix is None:
        return name
    if type_ == '堂区' and name.endswith('堂') and len(name) >= 3:
        name = name[:-1]
    if name.endswith(suffix) and len(name) > len(suffix):
        return f'{name[:-len(suffix)]}:{suffix}'
    return f'{name}:{suffix}'


def proper_of(name):
    """取「专名:通名」里的专名"""
    return name.split(':')[0]
